"""Shared utilities for reproducible QMeL regression experiments.

All series use one-based ``round`` in CSV files. Aggregation always applies
alpha-fairness *within each seed* before computing cross-seed statistics.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Iterable

import numpy as np
import pandas as pd


OUTPUT_MARKER = '.qmel_rerun_output'


def alpha_fairness(u: np.ndarray, alpha: float) -> np.ndarray:
    """Per-user alpha-fairness (NOT summed over users)."""
    u = np.asarray(u, dtype=np.float64)
    if not np.all(np.isfinite(u)) or np.any(u <= 0):
        raise ValueError('Alpha-fairness requires finite, strictly positive utilities')
    if np.isclose(alpha, 1.0):
        return np.log(u)
    return np.expm1((1.0 - alpha) * np.log(u)) / (1.0 - alpha)


def first_crossing(values: np.ndarray, threshold: float) -> int | None:
    idx = np.flatnonzero(np.isfinite(values) & (values <= threshold))
    return int(idx[0] + 1) if idx.size else None


def sustained_crossing(values: np.ndarray, threshold: float) -> int | None:
    """Earliest round after which *every* remaining round is below threshold."""
    good = np.isfinite(values) & (values <= threshold)
    suffix = np.logical_and.accumulate(good[::-1])[::-1]
    idx = np.flatnonzero(suffix)
    return int(idx[0] + 1) if idx.size else None


def parse_csv_list(spec: str, cast) -> list:
    items = [cast(x.strip()) for x in spec.split(',') if x.strip()]
    if not items or len(items) != len(set(items)):
        raise ValueError('Expected a nonempty, comma-separated list of distinct values')
    return items


def prepare_output(path: str | Path, overwrite: bool) -> Path:
    path = Path(path)
    if path.exists() and any(path.iterdir()):
        if not overwrite:
            raise FileExistsError(
                f'{path} already has contents; choose --output or pass --overwrite'
            )
        if not (path / OUTPUT_MARKER).is_file():
            raise ValueError(
                f'Refusing to clear {path}: missing {OUTPUT_MARKER} marker'
            )
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)
    (path / OUTPUT_MARKER).write_text('Generated by QMeL regression experiments.\n')
    (path / 'trajectories').mkdir(exist_ok=True)
    (path / 'user_histories').mkdir(exist_ok=True)
    (path / 'aggregated').mkdir(exist_ok=True)
    return path


def write_json(path: Path, payload: dict) -> None:
    def coerce(obj):
        if isinstance(obj, (np.integer, np.floating)):
            return obj.item()
        if isinstance(obj, np.ndarray):
            return obj.tolist()
        if isinstance(obj, Path):
            return str(obj)
        raise TypeError(f'Cannot serialize {type(obj)}')

    path.write_text(json.dumps(payload, indent=2, default=coerce) + '\n')


def aggregate_trajectories(runs: Iterable[pd.DataFrame]) -> pd.DataFrame:
    """Pointwise means/std across seeds; one row per round.

    ``*_std`` is the *sample* standard deviation (ddof=1). For a single run
    it is NaN, not a misleading zero.
    """
    frames = list(runs)
    if not frames:
        raise ValueError('No runs to aggregate')
    rounds = frames[0]['round'].to_numpy()
    cols = [c for c in frames[0] if c != 'round']
    for frame in frames[1:]:
        if not np.array_equal(rounds, frame['round'].to_numpy()):
            raise ValueError('Nonmatching rounds in aggregation')
        if cols != [c for c in frame if c != 'round']:
            raise ValueError('Nonmatching metric columns in aggregation')

    result = pd.DataFrame({'round': rounds, 'n_seeds': len(frames)})
    for col in cols:
        stack = np.stack([f[col].to_numpy(dtype=np.float64) for f in frames])
        result[f'{col}_mean'] = np.mean(stack, axis=0)
        result[f'{col}_std'] = (
            np.std(stack, axis=0, ddof=1)
            if len(frames) >= 2 else np.full_like(stack[0], np.nan)
        )
    return result


def assert_finite(name: str, array: np.ndarray) -> None:
    if not np.all(np.isfinite(array)):
        raise AssertionError(f'Non-finite values in {name}')
